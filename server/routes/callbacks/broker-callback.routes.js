import { Router } from "express";
import { receiveAuthCode, failAuthSession } from "../../services/auth-sessions.service.js";
import { completeAuthSessionV2 } from "../../services/auth-sessions-v2.service.js";
import { getProvider } from "../../providers/provider-registry.js";
import { isSealedState } from "../../security/crypto.js";
import { limitCallbacks } from "../../middleware/rate-limits.js";

const ALLOWED_STATUSES = new Set(["received", "failed", "invalid", "unavailable", "expired"]);

function redirectToResponse(res, broker, status) {
    res.set({
        "Cache-Control": "no-store",
        "Referrer-Policy": "no-referrer",
        "X-Content-Type-Options": "nosniff",
        "Content-Security-Policy": "default-src 'none'; base-uri 'none'; frame-ancestors 'none'"
    });

    const safeStatus = ALLOWED_STATUSES.has(status) ? status : "invalid";

    return res.redirect(
        303,
        `/auth/response?broker=${encodeURIComponent(broker)}&status=${encodeURIComponent(safeStatus)}`
    );
}

/** One callback route for every broker: GET /auth/:broker/callback */
export default function createBrokerCallbackRouter(env) {
    const router = Router({ mergeParams: true });

    router.get("/callback", limitCallbacks(env), async (req, res) => {
        const broker = req.params.broker;
        const { code, state, error } = req.query;

        try {
            const provider = getProvider(env, broker);

            if (!provider || typeof state !== "string") {
                return redirectToResponse(res, provider ? broker : "corex", "invalid");
            }

            // v2: sealed state, token exchange happens here.
            if (isSealedState(state)) {
                const status = await completeAuthSessionV2(env, provider, { state, code, error });
                return redirectToResponse(res, broker, status);
            }

            // v1 (deprecated): store the code for the client to exchange itself.
            if (typeof error === "string" && error.length > 0) {
                const updated = await failAuthSession(env, { broker, state });
                return redirectToResponse(res, broker, updated ? "failed" : "invalid");
            }

            if (typeof code !== "string" || code.length === 0) {
                return redirectToResponse(res, broker, "invalid");
            }

            const accepted = await receiveAuthCode(env, { broker, code, state });
            return redirectToResponse(res, broker, accepted ? "received" : "invalid");
        } catch (err) {
            console.error("Callback processing failed:", err instanceof Error ? err.message : "Unknown error");
            return redirectToResponse(res, "corex", "unavailable");
        }
    });

    // Compatibility route for links generated by the previous implementation.
    router.get("/complete", (req, res) => {
        const status = typeof req.query.status === "string" ? req.query.status : "invalid";
        return redirectToResponse(res, req.params.broker, status);
    });

    return router;
}
