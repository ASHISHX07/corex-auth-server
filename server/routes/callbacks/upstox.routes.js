import { Router } from "express";
import {
    receiveAuthCode,
    failAuthSession
} from "../../services/auth-sessions.service.js";
import { limitUpstoxCallbacks } from "../../middleware/rate-limits.js";

const ALLOWED_STATUSES = new Set([
    "received",
    "failed",
    "invalid",
    "unavailable",
    "expired"
]);

function protectResponse(res) {
    res.set({
        "Cache-Control": "no-store",
        "Referrer-Policy": "no-referrer",
        "X-Content-Type-Options": "nosniff",
        "Content-Security-Policy":
            "default-src 'none'; " +
            "base-uri 'none'; " +
            "frame-ancestors 'none'"
    });
}

function redirectToResponse(res, status) {
    protectResponse(res);

    const safeStatus = ALLOWED_STATUSES.has(status)
        ? status
        : "invalid";

    return res.redirect(
        303,
        `/auth/response?broker=upstox&status=${encodeURIComponent(safeStatus)}`
    );
}

function createUpstoxCallbackRouter(env) {
    const router = Router();

    router.get("/callback", limitUpstoxCallbacks(env), async (req, res) => {
        const { code, state, error } = req.query;

        try {
            if (typeof state !== "string") {
                return redirectToResponse(res, "invalid");
            }

            if (typeof error === "string" && error.length > 0) {
                const updated = await failAuthSession(env, {
                    broker: "upstox",
                    state
                });

                return redirectToResponse(
                    res,
                    updated ? "failed" : "invalid"
                );
            }

            if (
                typeof code !== "string" ||
                code.length === 0
            ) {
                return redirectToResponse(res, "invalid");
            }

            const accepted = await receiveAuthCode(env, {
                broker: "upstox",
                code,
                state
            });

            return redirectToResponse(
                res,
                accepted ? "received" : "invalid"
            );
        } catch (error) {
            console.error(
                "Callback processing failed:",
                error instanceof Error ? error.message : "Unknown error"
            );

            return redirectToResponse(res, "unavailable");
        }
    });

    // Compatibility route for links generated by the previous implementation.
    router.get("/complete", (req, res) => {
        const status =
            typeof req.query.status === "string" &&
            ALLOWED_STATUSES.has(req.query.status)
                ? req.query.status
                : "invalid";

        return redirectToResponse(res, status);
    });

    return router;
}

export default createUpstoxCallbackRouter;